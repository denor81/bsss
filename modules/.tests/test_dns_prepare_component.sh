    fi
    /usr/bin/ln "$@"
}

# @type:        Source
# @description: Reports real metadata with root uid and gid
# @params:      options stat options and path
# @stdin:       None
# @stdout:      Requested metadata
# @exit_code:   $? real stat status
stat() {
    local option="$1"
    local format="$2"
    local path="$3"
    local mode links type size device inode

    [[ "$option" == "-c" ]] || return 1
    mode=$(/usr/bin/stat -c '%a' "$path") || return 1
    links=$(/usr/bin/stat -c '%h' "$path") || return 1
    type=$(/usr/bin/stat -c '%F' "$path") || return 1
    size=$(/usr/bin/stat -c '%s' "$path") || return 1
    device=$(/usr/bin/stat -c '%d' "$path") || return 1
    inode=$(/usr/bin/stat -c '%i' "$path") || return 1

    case "$format" in
        $'%u\t%g\t%a') printf '0\t0\t%s\n' "$mode" ;;
        $'%u\t%g\t%a\t%h\t%F') printf '0\t0\t%s\t%s\t%s\n' "$mode" "$links" "$type" ;;
        $'%u\t%g\t%h\t%F') printf '0\t0\t%s\t%s\n' "$links" "$type" ;;
        $'%s\t%u\t%g\t%a') printf '%s\t0\t0\t%s\n' "$size" "$mode" ;;
        $'%d\t%i\t%s\t%u\t%g\t%a') printf '%s\t%s\t%s\t0\t0\t%s\n' "$device" "$inode" "$size" "$mode" ;;
        *) return 1 ;;
    esac
}

# @type:        Orchestrator
# @description: Models systemd-resolved unit transitions and properties
# @stdin:       None
# @stdout:      property_value\n for show
# @exit_code:   0 supported command
#               1 unsupported command or property
systemctl() {
    local command="$1"
    local service="${2:-}"
    local property="${3:-}"
    property="${property#--property=}"

    [[ "$command" != "$SYSTEMCTL_FAILURE" ]] || return 1
    case "$command" in
        show)
            case "${service}:${property}" in
                "${DNS_RESOLVED_SERVICE}:LoadState") printf 'loaded\n' ;;
                "${DNS_RESOLVED_SERVICE}:UnitFileState") printf '%s\n' "$RESOLVED_ENABLED" ;;
                "${DNS_RESOLVED_SERVICE}:ActiveState") printf '%s\n' "$RESOLVED_ACTIVE" ;;
                "${DNS_RESOLVED_SERVICE}:SubState") printf '%s\n' "$RESOLVED_SUBSTATE" ;;
                "${DNS_NETWORKD_SERVICE}:ActiveState") printf 'active\n' ;;
                "${DNS_NETWORKD_SERVICE}:SubState") printf 'running\n' ;;
                "${DNS_NETWORK_MANAGER_SERVICE}:ActiveState") printf 'inactive\n' ;;
                *) return 1 ;;
            esac
            ;;
        enable)
            RESOLVED_ENABLED="enabled"
            ;;
        start)
            RESOLVED_ACTIVE="active"
            RESOLVED_SUBSTATE="running"
            ;;
        stop)
            [[ -f "$DNS_RESOLV_CONF_PATH" && ! -L "$DNS_RESOLV_CONF_PATH" ]] ||
                return 1
            RESOLVED_ACTIVE="inactive"
            RESOLVED_SUBSTATE="dead"
            ;;
        disable)
            RESOLVED_ENABLED="disabled"
            ;;
        *)
            return 1
            ;;
    esac
}

