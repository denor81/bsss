set -Eeuo pipefail

readonly PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
readonly TEST_TMP="$(mktemp -d "${TMPDIR:-/tmp}/bsss-dns-diagnostics-test.XXXXXX")"
trap 'rm -rf "$TEST_TMP"' EXIT

readonly OS_RELEASE_FILE_PATH="${TEST_TMP}/os-release"
readonly DNS_PROFILE_GOOGLE_CLOUDFLARE="google-cloudflare"
readonly DNS_PROFILE_YANDEX_GOOGLE="yandex-google"
readonly DNS_DEFAULT_PROFILE="$DNS_PROFILE_GOOGLE_CLOUDFLARE"
readonly DNS_SERVERS_GOOGLE_CLOUDFLARE="8.8.8.8#dns.google 1.1.1.1#one.one.one.one"
readonly DNS_SERVERS_YANDEX_GOOGLE="77.88.8.8#common.dot.dns.yandex.net 8.8.8.8#dns.google"
readonly DNS_SUPPORTED_UBUNTU_VERSIONS="22.04|24.04|26.04"
readonly DNS_RESOLVED_SERVICE="systemd-resolved.service"
readonly DNS_RESOLV_CONF_PATH="${TEST_TMP}/etc/resolv.conf"
readonly DNS_RESOLVED_STUB_PATH="${TEST_TMP}/run/systemd/resolve/stub-resolv.conf"
readonly DNS_RESOLVED_CONFIG_DIR="${TEST_TMP}/etc/systemd/resolved.conf.d"
readonly BSSS_DNS_CONFIG_FILE_NAME="99-bsss-dot.conf"
readonly BSSS_DNS_CONFIG_FILE="${DNS_RESOLVED_CONFIG_DIR}/${BSSS_DNS_CONFIG_FILE_NAME}"
readonly BSSS_MARKER_COMMENT="Generated by BSSS"

mkdir -p "$DNS_RESOLVED_CONFIG_DIR"
printf 'ID=ubuntu\nVERSION_ID=24.04\n' > "$OS_RELEASE_FILE_PATH"

source "${PROJECT_ROOT}/modules/helpers/dns/facade.sh"

RESOLVED_ACTIVE="active"
RUNTIME_DNS="$DNS_SERVERS_GOOGLE_CLOUDFLARE"
RUNTIME_DOMAINS="~."
RUNTIME_DOT="yes"
GLOBAL_CALL_LOG="${TEST_TMP}/global-calls"
WARN_LOG="${TEST_TMP}/warn"
INFO_LOG="${TEST_TMP}/info"
TAB_LOG="${TEST_TMP}/tab"

# @type:        Sink
# @description: Fails the current test
# @params:      message Failure message (string) without a terminator
# @stdin:       None
# @stdout:      None
# @exit_code:   1 always
test::fail() {
    printf 'FAIL: %s\n' "$1" >&2
    exit 1
}

# @type:        Validator
# @description: Checks whether a string contains a fragment
# @params:      text Complete string (string) without a terminator
#               fragment Expected fragment (string) without a terminator
#               label Assertion label (string) without a terminator
# @stdin:       None
# @stdout:      None
# @exit_code:   0 fragment found
#               1 fragment absent
test::assert::contains() {
    [[ "$1" == *"$2"* ]] || test::fail "$3: missing [$2] in [$1]"
}

# @type:        Source
# @description: Emits exact effective settings
# @stdin:       None
# @stdout:      setting<TAB>value\0 (7 records)
# @exit_code:   0 always
test::effective() {
    printf '%s\t%s\0' \
        "DNS" "$DNS_SERVERS_GOOGLE_CLOUDFLARE" \
        "FallbackDNS" "" \
        "Domains" "~." \
        "DNSOverTLS" "yes" \
        "DNSSEC" "no" \
        "LLMNR" "no" \
        "MulticastDNS" "no"
}

dns::config::get_effective() {
    test::effective
}

dns::config::is_owned() {
    return
}

dns::state::unit_property() {
    printf '%s\n' "$RESOLVED_ACTIVE"
}

readlink() {
    printf '%s\n' "$DNS_RESOLVED_STUB_PATH"
}

dns::runtime::stub_is_listening() {
    return
}

dns::runtime::local_resolvers() {
    return
}

dns::runtime::route_domains() {
    return
}

dns::runtime::get_global() {
    printf '%s\n' "$1" >> "$GLOBAL_CALL_LOG"
    case "$1" in
        dns) printf '%s\0' "$RUNTIME_DNS" ;;
        domain) printf '%s\0' "$RUNTIME_DOMAINS" ;;
        dnsovertls) printf '%s\0' "$RUNTIME_DOT" ;;
        *) return 1 ;;
    esac
}

issues=$(dns::diagnostics::issues | tr '\0' '\n')
[[ -z "$issues" ]] ||
    test::fail "protected diagnostics emitted issues: $issues"
dns::diagnostics::is_protected ||
    test::fail "protected diagnostics were rejected"

effective_issues=$(
    printf '%s\t%s\0' \
        "DNS" "9.9.9.9#dns.quad9.net" \
        "FallbackDNS" "1.1.1.1" \
        "Domains" "corp.example" \
        "DNSOverTLS" "opportunistic" \
        "DNSSEC" "yes" \
        "LLMNR" "yes" \
        "MulticastDNS" "yes" |
        dns::diagnostics::effective_issues |
        tr '\0' '\n'
)
for code in profile_unknown fallback_dns domains dot_mode dnssec llmnr multicast_dns; do
    test::assert::contains "$effective_issues" "$code" "effective issue $code"
done

RESOLVED_ACTIVE="inactive"
: > "$GLOBAL_CALL_LOG"
issues=$(dns::diagnostics::issues | tr '\0' '\n')
test::assert::contains "$issues" "resolved_inactive" "inactive resolved issue"
[[ ! -s "$GLOBAL_CALL_LOG" ]] ||
    test::fail "inactive resolved still inspected Global runtime"

_() {
    local key="$1"
    shift
    printf '%s' "$key"
    if (( $# > 0 )); then
        printf '|%s' "$*"
    fi
}

log_info() {
    printf '%s\n' "$1" >> "$INFO_LOG"
}

log_warn() {
    printf '%s\n' "$1" >> "$WARN_LOG"
}

log_info_simple_tab() {
    printf '%s\n' "$1" >> "$TAB_LOG"
}

dns::diagnostics::is_protected() {
    return 1
}

dns::diagnostics::issues() {
    dns::check::emit "dot_mode" "no"
    dns::check::emit "runtime_dot" "no"
}

: > "$WARN_LOG"
: > "$TAB_LOG"
dns::presentation::status
[[ "$(wc -l < "$WARN_LOG")" == "1" ]] ||
    test::fail "unprotected status did not emit one warning"
tab_log=$(cat "$TAB_LOG")
test::assert::contains "$tab_log" "dns.issue.dot_mode|no" "tabbed config issue"
test::assert::contains "$tab_log" "dns.issue.runtime_dot|no" "tabbed runtime issue"

printf 'All DNS diagnostics and presentation tests passed\n'
