set -Eeuo pipefail

readonly PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
readonly TEST_TMP="$(mktemp -d "${TMPDIR:-/tmp}/bsss-dns-config-test.XXXXXX")"
trap 'rm -rf "$TEST_TMP"' EXIT

readonly BSSS_MARKER_COMMENT="Generated by BSSS"
readonly DNS_PROFILE_GOOGLE_CLOUDFLARE="google-cloudflare"
readonly DNS_PROFILE_YANDEX_GOOGLE="yandex-google"
readonly DNS_SERVERS_GOOGLE_CLOUDFLARE="8.8.8.8#dns.google 1.1.1.1#one.one.one.one"
readonly DNS_SERVERS_YANDEX_GOOGLE="77.88.8.8#common.dot.dns.yandex.net 8.8.8.8#dns.google"
readonly DNS_RESOLVED_CONFIG_DIR="${TEST_TMP}/etc/systemd/resolved.conf.d"
readonly BSSS_DNS_CONFIG_FILE_NAME="99-bsss-dot.conf"
readonly BSSS_DNS_CONFIG_FILE="${DNS_RESOLVED_CONFIG_DIR}/${BSSS_DNS_CONFIG_FILE_NAME}"

readonly TEST_VENDOR_DIR="${TEST_TMP}/usr/lib/systemd/resolved.conf.d"
readonly TEST_ETC_DIR="$DNS_RESOLVED_CONFIG_DIR"

mkdir -p "$TEST_VENDOR_DIR" "$TEST_ETC_DIR"

source "${PROJECT_ROOT}/modules/helpers/dns/facade.sh"

# @type:        Sink
# @description: Fails the current test
# @params:      message Failure message (string) without a terminator
# @stdin:       None
# @stdout:      None
# @exit_code:   1 always
test::fail() {
    printf 'FAIL: %s\n' "$1" >&2
    exit 1
}

# @type:        Validator
# @description: Compares two strings
# @params:      expected Expected value (string) without a terminator
#               actual Actual value (string) without a terminator
#               label Assertion label (string) without a terminator
# @stdin:       None
# @stdout:      None
# @exit_code:   0 values match
#               1 values differ
test::assert::equals() {
    [[ "$2" == "$1" ]] || test::fail "$3: expected [$1], got [$2]"
}

# @type:        Source
# @description: Overrides resolved drop-in search directories for the focused test
# @stdin:       None
# @stdout:      path\0 (2 records)
# @exit_code:   0 paths emitted
dns::config::search_dirs() {
    printf '%s\0' "$TEST_VENDOR_DIR" "$TEST_ETC_DIR"
}

dns::profile::is_valid "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
    test::fail "Google and Cloudflare profile was rejected"
dns::profile::is_valid "$DNS_PROFILE_YANDEX_GOOGLE" ||
    test::fail "Yandex and Google profile was rejected"
if dns::profile::is_valid "unknown"; then
    test::fail "unknown profile was accepted"
fi

servers=$(dns::profile::get_servers "$DNS_PROFILE_GOOGLE_CLOUDFLARE" | tr -d '\0')
test::assert::equals "$DNS_SERVERS_GOOGLE_CLOUDFLARE" "$servers" "profile servers"

endpoints=$(dns::profile::get_endpoints "$DNS_PROFILE_YANDEX_GOOGLE" | tr '\0' '\n')
expected_endpoints=$'77.88.8.8\tcommon.dot.dns.yandex.net\n8.8.8.8\tdns.google'
test::assert::equals "$expected_endpoints" "$endpoints" "profile endpoints"

dns::config::render "$DNS_PROFILE_GOOGLE_CLOUDFLARE" > "$BSSS_DNS_CONFIG_FILE"
dns::config::is_owned "$BSSS_DNS_CONFIG_FILE" ||
    test::fail "rendered BSSS configuration was not recognized"
dns::config::matches_profile "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
    test::fail "rendered profile did not match itself"
if dns::config::matches_profile "$DNS_PROFILE_YANDEX_GOOGLE"; then
    test::fail "different profile matched rendered configuration"
fi

parsed=$(
    cat << 'EOF' |
[Resolve]
DNS=192.0.2.1
DNS=
DNS=8.8.8.8#dns.google
FallbackDNS=1.1.1.1
FallbackDNS=
Domains=example.test
Domains=
Domains=~.
DNSOverTLS=yes
DNSSEC=no
LLMNR=no
MulticastDNS=no
EOF
        dns::config::parse_effective |
        tr '\0' '\n'
)
expected=$'DNS\t8.8.8.8#dns.google\nFallbackDNS\t\nDomains\t~.\nDNSOverTLS\tyes\nDNSSEC\tno\nLLMNR\tno\nMulticastDNS\tno'
test::assert::equals "$expected" "$parsed" "effective list reset parsing"

printf '%s\n' '[Resolve]' 'Cache=yes' > "${TEST_VENDOR_DIR}/98-cache.conf"
printf '%s\n' '[Resolve]' 'DNS=9.9.9.9#dns.quad9.net' > "${TEST_VENDOR_DIR}/zz-foreign.conf"
printf '%s\n' '[Resolve]' 'DNS=192.0.2.53' > "${TEST_ETC_DIR}/90-early.conf"
conflicts=$(dns::config::late_conflicts | tr '\0' '\n')
test::assert::equals "${TEST_VENDOR_DIR}/zz-foreign.conf" "$conflicts" "late conflict detection"

printf 'All DNS configuration component tests passed\n'
