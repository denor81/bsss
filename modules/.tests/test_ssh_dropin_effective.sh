#!/usr/bin/env bash

set -Eeuo pipefail

readonly PROJECT_ROOT="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && realpath ../..)"
readonly TEST_TMP_DIR="$(mktemp -d)"
readonly SSH_CONFIGD_DIR="${TEST_TMP_DIR}/sshd_config.d"
readonly BSSS_SSH_CONFIG_FILE_NAME="40-bsss-ssh-port.conf"
readonly BSSS_PERMISSIONS_CONFIG_FILE_NAME="-bsss-permissions.conf"
readonly BSSS_MARKER_COMMENT="Generated by BSSS"

trap 'rm -rf "$TEST_TMP_DIR"' EXIT

test::fail() {
    printf 'FAIL: %s\n' "$1" >&2
    exit 1
}

_() {
    printf '%s' "$1"
}

log_info() {
    :
}

log_error() {
    printf '%s\n' "$*" >> "${TEST_TMP_DIR}/errors"
}

sshd() {
    [[ "$1" == "-t" ]]
}

source "${PROJECT_ROOT}/modules/helpers/ssh-port.sh"
source "${PROJECT_ROOT}/modules/helpers/permissions.sh"

EFFECTIVE_PORT="44000"
ssh::port::get_configured() {
    printf '%s\0' "$EFFECTIVE_PORT"
}

printf '44000\0' | ssh::config::create_bsss_file ||
    test::fail "effective SSH port file was rejected"
[[ -f "${SSH_CONFIGD_DIR}/${BSSS_SSH_CONFIG_FILE_NAME}" ]] ||
    test::fail "effective SSH port file was not retained"

EFFECTIVE_PORT="22"
if printf '44000\0' | ssh::config::create_bsss_file; then
    test::fail "ineffective SSH port file was retained"
fi
[[ ! -e "${SSH_CONFIGD_DIR}/${BSSS_SSH_CONFIG_FILE_NAME}" ]] ||
    test::fail "ineffective SSH port file was not removed"

permissions::config::find_last_prefix() {
    :
}

PERMISSIONS_EFFECTIVE=0
permissions::rules::is_effective() {
    (( PERMISSIONS_EFFECTIVE == 1 ))
}

PERMISSIONS_EFFECTIVE=1
permissions::rules::make_bsss_rules >/dev/null ||
    test::fail "effective permissions file was rejected"
[[ -f "${SSH_CONFIGD_DIR}/10${BSSS_PERMISSIONS_CONFIG_FILE_NAME}" ]] ||
    test::fail "effective permissions file was not retained"

rm "${SSH_CONFIGD_DIR}/10${BSSS_PERMISSIONS_CONFIG_FILE_NAME}"
PERMISSIONS_EFFECTIVE=0
if permissions::rules::make_bsss_rules >/dev/null; then
    test::fail "ineffective permissions file was retained"
fi
[[ ! -e "${SSH_CONFIGD_DIR}/10${BSSS_PERMISSIONS_CONFIG_FILE_NAME}" ]] ||
    test::fail "ineffective permissions file was not removed"

printf 'PASS: SSH drop-in effective validation\n'
