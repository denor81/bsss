set -Eeuo pipefail

readonly PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
readonly TEST_TMP="$(mktemp -d "${TMPDIR:-/tmp}/bsss-dns-recovery-test.XXXXXX")"
trap 'rm -rf "$TEST_TMP"' EXIT

readonly BSSS_MARKER_COMMENT="Generated by BSSS"
readonly DNS_PROFILE_GOOGLE_CLOUDFLARE="google-cloudflare"
readonly DNS_PROFILE_YANDEX_GOOGLE="yandex-google"
readonly DNS_SERVERS_GOOGLE_CLOUDFLARE="8.8.8.8#dns.google 1.1.1.1#one.one.one.one"
readonly DNS_SERVERS_YANDEX_GOOGLE="77.88.8.8#common.dot.dns.yandex.net 8.8.8.8#dns.google"
readonly DNS_SUPPORTED_UBUNTU_VERSIONS="22.04|24.04|26.04"
readonly DNS_BOOTSTRAP_SUPPORTED_UBUNTU_VERSIONS="24.04"
readonly DNS_RESOLVED_SERVICE="systemd-resolved.service"
readonly DNS_NETWORKD_SERVICE="systemd-networkd.service"
readonly DNS_NETWORK_MANAGER_SERVICE="NetworkManager.service"
readonly DNS_RESOLVED_CONFIG_DIR="${TEST_TMP}/etc/systemd/resolved.conf.d"
readonly BSSS_DNS_CONFIG_FILE_NAME="99-bsss-dot.conf"
readonly BSSS_DNS_CONFIG_FILE="${DNS_RESOLVED_CONFIG_DIR}/${BSSS_DNS_CONFIG_FILE_NAME}"
readonly BSSS_DNS_ROLLBACK_FILE="${BSSS_DNS_CONFIG_FILE}.bsss_backup"
readonly DNS_RESOLV_CONF_PATH="${TEST_TMP}/etc/resolv.conf"
readonly DNS_RESOLVED_STUB_PATH="${TEST_TMP}/run/systemd/resolve/stub-resolv.conf"
readonly DNS_TEST_DOMAIN="example.com"
readonly DNS_ENDPOINT_TIMEOUT_SECONDS=10
readonly DNS_QUERY_TIMEOUT_SECONDS=15
readonly BSSS_STATE_DIR="${TEST_TMP}/var/lib/bsss"
readonly DNS_PREPARE_DIR="${BSSS_STATE_DIR}/dns-resolver-prepare"
readonly DNS_PREPARE_STAGING_DIR="${BSSS_STATE_DIR}/.dns-resolver-prepare.new"
readonly DNS_PREPARE_CLEANUP_DIR="${BSSS_STATE_DIR}/.dns-resolver-prepare.cleanup"
readonly DNS_PREPARE_STATE_FILE="${DNS_PREPARE_DIR}/state"
readonly DNS_PREPARE_BACKUP_FILE="${DNS_PREPARE_DIR}/resolv.conf"
readonly DNS_PREPARE_TEMP_LINK="${TEST_TMP}/etc/.resolv.conf.bsss_prepare"
readonly DNS_PREPARE_LOCK_FILE="${TEST_TMP}/run/lock/bsss-dns-prepare.lock"
readonly HOSTS_FILE_PATH="${TEST_TMP}/etc/hosts"
readonly OS_RELEASE_FILE_PATH="${TEST_TMP}/etc/os-release"
DNS_PREPARE_LOCK_FD=""
SYNC_FAILURE=0
SYNC_CALLS=""

mkdir -p \
    "$(dirname "$DNS_RESOLV_CONF_PATH")" \
    "$(dirname "$DNS_RESOLVED_STUB_PATH")" \
    "$(dirname "$DNS_PREPARE_LOCK_FILE")" \
    "${TEST_TMP}/var/lib"
touch "$DNS_RESOLVED_STUB_PATH"

# @type:        Sink
# @description: Fails the current test
# @params:      message Failure message (string) without a terminator
# @stdin:       None
# @stdout:      None
# @exit_code:   1 always
test::fail() {
    printf 'FAIL: %s\n' "$1" >&2
    exit 1
}

# @type:        Validator
# @description: Compares two strings
# @params:      expected Expected value (string) without a terminator
#               actual Actual value (string) without a terminator
#               label Assertion label (string) without a terminator
# @stdin:       None
# @stdout:      None
# @exit_code:   0 values match
#               1 values differ
test::assert::equals() {
    [[ "$2" == "$1" ]] || test::fail "$3: expected [$1], got [$2]"
}

# @type:        Sink
# @description: Mocks root ownership updates in an unprivileged test
# @stdin:       None
# @stdout:      None
# @exit_code:   0 always
chown() { :; }

# @type:        Sink
# @description: Records or fails filesystem flushes
# @params:      options sync arguments
# @stdin:       None
# @stdout:      None
# @exit_code:   0 flush accepted
#               1 injected failure
sync() {
    SYNC_CALLS+="${2:-} "
    (( SYNC_FAILURE == 0 ))
}

# @type:        Source
# @description: Reports real metadata with root uid and gid
# @params:      options stat options and path
# @stdin:       None
# @stdout:      Requested metadata
# @exit_code:   $? real stat status
stat() {
    local option="$1"
    local format="$2"
    local path="$3"
    local mode links type size device inode

    [[ "$option" == "-c" ]] || return 1
    mode=$(/usr/bin/stat -c '%a' "$path") || return 1
    links=$(/usr/bin/stat -c '%h' "$path") || return 1
    type=$(/usr/bin/stat -c '%F' "$path") || return 1
    size=$(/usr/bin/stat -c '%s' "$path") || return 1
    device=$(/usr/bin/stat -c '%d' "$path") || return 1
    inode=$(/usr/bin/stat -c '%i' "$path") || return 1

    case "$format" in
        $'%u\t%g\t%a') printf '0\t0\t%s\n' "$mode" ;;
        $'%u\t%g\t%a\t%h\t%F') printf '0\t0\t%s\t%s\t%s\n' "$mode" "$links" "$type" ;;
        $'%u\t%g\t%h\t%F') printf '0\t0\t%s\t%s\n' "$links" "$type" ;;
        $'%s\t%u\t%g\t%a') printf '%s\t0\t0\t%s\n' "$size" "$mode" ;;
        $'%d\t%i\t%s\t%u\t%g\t%a') printf '%s\t%s\t%s\t0\t0\t%s\n' "$device" "$inode" "$size" "$mode" ;;
        *) return 1 ;;
    esac
}

source "${PROJECT_ROOT}/modules/helpers/dns/facade.sh"

printf '%s\n' \
    '# direct resolver' \
    'nameserver 8.8.8.8' \
    'nameserver 2001:4860:4860::8888' > "$DNS_RESOLV_CONF_PATH"

fingerprint=$(dns::recovery::fingerprint | tr -d '\0')
[[ "$fingerprint" == *$'\t'* ]] || test::fail "resolver fingerprint was not emitted"

exec {busy_fd}> "$DNS_PREPARE_LOCK_FILE"
flock -n "$busy_fd"
if dns::recovery::lock; then
    test::fail "busy recovery lock was acquired"
else
    test::assert::equals "4" "$?" "busy recovery lock status"
fi
exec {busy_fd}>&-
dns::recovery::lock || test::fail "free recovery lock was not acquired"
dns::recovery::unlock

dns::recovery::create_bundle "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
    test::fail "recovery bundle creation failed"
bundle=$(dns::recovery::read_bundle "$DNS_PREPARE_DIR" | tr -d '\0')
test::assert::equals \
    "${DNS_PROFILE_GOOGLE_CLOUDFLARE}"$'\t'"$(sha256sum "$DNS_RESOLV_CONF_PATH" | gawk '{ print $1 }')" \
    "$bundle" \
    "bundle manifest"
cmp --silent "$DNS_RESOLV_CONF_PATH" "$DNS_PREPARE_BACKUP_FILE" ||
    test::fail "bundle resolver bytes differ"

cp "$DNS_PREPARE_STATE_FILE" "${TEST_TMP}/valid-state"
sed 's/^profile	/profile /' "${TEST_TMP}/valid-state" > "$DNS_PREPARE_STATE_FILE"
if dns::recovery::read_bundle "$DNS_PREPARE_DIR" >/dev/null; then
    test::fail "manifest with a space separator was accepted"
fi
mv "${TEST_TMP}/valid-state" "$DNS_PREPARE_STATE_FILE"

printf 'changed\n' > "$DNS_RESOLV_CONF_PATH"
dns::recovery::restore_resolv_conf ||
    test::fail "resolver restoration failed"
cmp --silent "$DNS_RESOLV_CONF_PATH" "$DNS_PREPARE_BACKUP_FILE" ||
    test::fail "restored resolver bytes differ"
[[ "$SYNC_CALLS" == *"${TEST_TMP}/etc "* ]] ||
    test::fail "resolver directory was not flushed"

dns::recovery::cleanup_bundle || test::fail "bundle cleanup failed"
[[ ! -e "$DNS_PREPARE_DIR" && ! -e "$DNS_PREPARE_CLEANUP_DIR" ]] ||
    test::fail "bundle cleanup left artifacts"

mkdir -m 700 "$DNS_PREPARE_STAGING_DIR"
touch "${DNS_PREPARE_STAGING_DIR}/state"
chmod 600 "${DNS_PREPARE_STAGING_DIR}/state"
dns::recovery::partial_is_owned "$DNS_PREPARE_STAGING_DIR" ||
    test::fail "owned partial directory was rejected"
dns::recovery::remove_partial "$DNS_PREPARE_STAGING_DIR" ||
    test::fail "owned partial directory was not removed"

mkdir -m 700 "$DNS_PREPARE_STAGING_DIR"
touch "${DNS_PREPARE_STAGING_DIR}/foreign"
if dns::recovery::partial_is_owned "$DNS_PREPARE_STAGING_DIR"; then
    test::fail "foreign partial entry was accepted"
fi
rm "${DNS_PREPARE_STAGING_DIR}/foreign"
rmdir "$DNS_PREPARE_STAGING_DIR"

ln -s "$DNS_RESOLVED_STUB_PATH" "$DNS_PREPARE_TEMP_LINK"
dns::recovery::remove_temp_link ||
    test::fail "owned temporary link was not removed"
ln -s "/foreign/stub" "$DNS_PREPARE_TEMP_LINK"
if dns::recovery::remove_temp_link; then
    test::fail "foreign temporary link was removed"
fi
rm "$DNS_PREPARE_TEMP_LINK"

SYNC_FAILURE=1
if dns::recovery::create_bundle "$DNS_PROFILE_GOOGLE_CLOUDFLARE"; then
    test::fail "bundle creation ignored a flush failure"
fi
SYNC_FAILURE=0
dns::recovery::partial_is_owned "$DNS_PREPARE_STAGING_DIR" ||
    test::fail "failed staging directory was not recoverable"
dns::recovery::remove_partial "$DNS_PREPARE_STAGING_DIR" ||
    test::fail "failed staging directory was not removed"

printf 'All DNS resolver recovery tests passed\n'
