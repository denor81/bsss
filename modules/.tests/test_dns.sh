# @type:        Source
# @description: Mocks UDP and TCP systemd-resolved stub listeners
# @stdin:       None
# @stdout:      ss listener rows separated by newlines
# @exit_code:   0 always
ss() {
    (( MOCK_STUB_AVAILABLE == 1 )) || return 0
    printf '%s\n' \
        'udp UNCONN 0 0 127.0.0.53%lo:53 0.0.0.0:*' \
        'tcp LISTEN 0 4096 127.0.0.53%lo:53 0.0.0.0:*'
}

# @type:        Source
# @description: Mocks effective resolved.conf output
# @stdin:       None
# @stdout:      resolved.conf text
# @exit_code:   0 supported command
#               1 unsupported command
systemd-analyze() {
    [[ "${1:-}" == "cat-config" ]] || return 1
    printf '%s\n' "$MOCK_CONFIG"
}

# @type:        Source
# @description: Mocks resolvectl global properties and per-link domains
# @stdin:       None
# @stdout:      resolvectl property rows
# @exit_code:   0 supported property
#               1 unsupported property
resolvectl() {
    printf '%s\n' "$*" >> "$TEST_RESOLVECTL_CALL_LOG"
    if (( MOCK_RESOLVECTL_FAILURE == 1 )); then
        printf 'mock D-Bus failure\n' >&2
        return 1
    fi

    if [[ "${2:-}" == "$MOCK_MALFORMED_PROPERTY" && -n "$MOCK_MALFORMED_PROPERTY" ]]; then
        printf 'malformed output\n'
        return
    fi

    case "${1:-}" in
        flush-caches) return ;;
        query)
            printf '%s: 192.0.2.1\n' "$DNS_TEST_DOMAIN"
            return
            ;;
    esac

    case "${2:-}" in
        dns)
            printf 'Global: %s\n' "$MOCK_GLOBAL_DNS"
            printf 'Link 2 (ens3): 192.0.2.53\n'
            ;;
        domain)
            printf 'Global: %s\n' "$MOCK_GLOBAL_DOMAINS"
            [[ -z "$MOCK_LINK_DOMAINS" ]] || printf '%s\n' "$MOCK_LINK_DOMAINS"
            ;;
        dnsovertls)
            printf 'Global: %s\n' "$MOCK_GLOBAL_DOT"
            printf 'Link 2 (ens3): no\n'
            ;;
        *)
            return 1
            ;;
    esac
}

# @type:        Orchestrator
# @description: Mocks bounded command execution
# @params:      duration Timeout duration (string) without a terminator
#               command Command and arguments without terminators
# @stdin:       None
# @stdout:      Wrapped command output
# @exit_code:   MOCK_TIMEOUT_EXIT or wrapped command status
timeout() {
    local duration="$1"
    shift
    : "$duration"

    (( MOCK_TIMEOUT_EXIT == 0 )) || return "$MOCK_TIMEOUT_EXIT"
    "$@"
}

