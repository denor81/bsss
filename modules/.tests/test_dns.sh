# @type:        Sink
# @description: Fails the current test with a message
# @params:      message Failure message (string) without a terminator
# @stdin:       None
# @stdout:      None
# @exit_code:   1 always
test::fail() {
    echo "FAIL: $1" >&2
    exit 1
}

# @type:        Validator
# @description: Compares two strings
# @params:      expected Expected value (string) without a terminator
#               actual Actual value (string) without a terminator
#               label Assertion label (string) without a terminator
# @stdin:       None
# @stdout:      None
# @exit_code:   0 values match
#               1 values differ
test::assert::equals() {
    local expected="$1" actual="$2" label="$3"

    [[ "$actual" == "$expected" ]] || test::fail "$label: expected [$expected], got [$actual]"
}

# @type:        Validator
# @description: Checks that text contains a literal fragment
# @params:      text Source text (string) without a terminator
#               fragment Required fragment (string) without a terminator
#               label Assertion label (string) without a terminator
# @stdin:       None
# @stdout:      None
# @exit_code:   0 fragment found
#               1 fragment absent
test::assert::contains() {
    local text="$1" fragment="$2" label="$3"

    [[ "$text" == *"$fragment"* ]] || test::fail "$label: missing [$fragment] in [$text]"
}

# @type:        Source
# @description: Returns translation keys and arguments in a deterministic test form
# @params:      key Translation key (string) without a terminator
#               ... Translation arguments without terminators
# @stdin:       None
# @stdout:      key|argument...
# @exit_code:   0 always
_() {
    local key="$1"
    shift

    printf '%s' "$key"
    printf '|%s' "$@"
}

