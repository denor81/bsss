set -Eeuo pipefail

readonly PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
readonly TEST_TMP="$(mktemp -d "${TMPDIR:-/tmp}/bsss-dns-validate-test.XXXXXX")"
trap 'rm -rf "$TEST_TMP"' EXIT

readonly OS_RELEASE_FILE_PATH="${TEST_TMP}/os-release"
readonly DNS_PROFILE_GOOGLE_CLOUDFLARE="google-cloudflare"
readonly DNS_PROFILE_YANDEX_GOOGLE="yandex-google"
readonly DNS_SERVERS_GOOGLE_CLOUDFLARE="8.8.8.8#dns.google 1.1.1.1#one.one.one.one"
readonly DNS_SERVERS_YANDEX_GOOGLE="77.88.8.8#common.dot.dns.yandex.net 8.8.8.8#dns.google"
readonly DNS_TEST_DOMAIN="example.com"
readonly DNS_QUERY_TIMEOUT_SECONDS=1
readonly BSSS_MARKER_COMMENT="Generated by BSSS"
readonly BSSS_DNS_CONFIG_FILE_NAME="99-bsss-dot.conf"
readonly DNS_RESOLVED_CONFIG_DIR="${TEST_TMP}/etc/systemd/resolved.conf.d"
readonly BSSS_DNS_CONFIG_FILE="${DNS_RESOLVED_CONFIG_DIR}/${BSSS_DNS_CONFIG_FILE_NAME}"

mkdir -p "$DNS_RESOLVED_CONFIG_DIR"
printf 'ID=ubuntu\nVERSION_ID=24.04\n' > "$OS_RELEASE_FILE_PATH"

source "${PROJECT_ROOT}/modules/helpers/dns/facade.sh"

TEST_STATUS=0
TEST_OUTPUT=""

# @type:        Sink
# @description: Fails the current test
# @params:      message Failure message (string) without a terminator
# @stdin:       None
# @stdout:      None
# @exit_code:   1 always
test::fail() {
    printf 'FAIL: %s\n' "$1" >&2
    exit 1
}

# @type:        Validator
# @description: Compares two strings
# @params:      expected Expected value (string) without a terminator
#               actual Actual value (string) without a terminator
#               label Assertion label (string) without a terminator
# @stdin:       None
# @stdout:      None
# @exit_code:   0 values match
#               1 values differ
test::assert::equals() {
    [[ "$2" == "$1" ]] || test::fail "$3: expected [$1], got [$2]"
}

# @type:        Orchestrator
# @description: Captures one validator status and NUL records
# @params:      command Function name (string) without a terminator
#               ... Function arguments (string) without a terminator
# @stdin:       None
# @stdout:      None
# @exit_code:   0 capture completed
test::capture() {
    local output_file="${TEST_TMP}/capture"

    : > "$output_file"
    if "$@" > "$output_file"; then
        TEST_STATUS=0
    else
        TEST_STATUS=$?
    fi
    TEST_OUTPUT=$(tr '\0' '\n' < "$output_file")
}

# @type:        Source
# @description: Emits exact effective settings for the default profile
# @stdin:       None
# @stdout:      setting<TAB>value\0 (7 records)
# @exit_code:   0 settings emitted
effective_stream() {
    printf '%s\t%s\0' \
        "DNS" "$DNS_SERVERS_GOOGLE_CLOUDFLARE" \
        "FallbackDNS" "" \
        "Domains" "~." \
        "DNSOverTLS" "yes" \
        "DNSSEC" "no" \
        "LLMNR" "no" \
        "MulticastDNS" "no"
}

effective_stream | dns::validate::effective_filter "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
    test::fail "exact effective settings were rejected"

output_file="${TEST_TMP}/mismatch"
if {
    printf '%s\t%s\0' \
        "DNS" "$DNS_SERVERS_GOOGLE_CLOUDFLARE" \
        "FallbackDNS" "1.1.1.1" \
        "Domains" "~." \
        "DNSOverTLS" "yes" \
        "DNSSEC" "no" \
        "LLMNR" "no" \
        "MulticastDNS" "no"
} | dns::validate::effective_filter "$DNS_PROFILE_GOOGLE_CLOUDFLARE" > "$output_file"; then
    test::fail "nonempty FallbackDNS was accepted"
else
    status=$?
fi
test::assert::equals "4" "$status" "effective mismatch status"
mismatch=$(tr '\0' '\n' < "$output_file")
test::assert::equals $'effective_mismatch\tFallbackDNS\t\t1.1.1.1' \
    "$mismatch" "effective mismatch issue"

if printf 'DNS\tvalue' | dns::validate::effective_filter "$DNS_PROFILE_GOOGLE_CLOUDFLARE" >/dev/null; then
    test::fail "unterminated effective record was accepted"
else
    status=$?
fi
test::assert::equals "1" "$status" "unterminated effective record status"

RUNTIME_DNS="8.8.8.8#dns.google 1.1.1.1#one.one.one.one"
RUNTIME_DOMAINS="~."
RUNTIME_DOT="yes"

# @type:        Source
# @description: Overrides normalized Global runtime values
# @params:      property Runtime property name (string) without a terminator
# @stdin:       None
# @stdout:      value\0
# @exit_code:   0 value emitted
#               1 unsupported property
dns::runtime::get_global() {
    case "$1" in
        dns) printf '%s\0' "$RUNTIME_DNS" ;;
        domain) printf '%s\0' "$RUNTIME_DOMAINS" ;;
        dnsovertls) printf '%s\0' "$RUNTIME_DOT" ;;
        *) return 1 ;;
    esac
}

dns::validate::global_runtime "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
    test::fail "exact runtime values were rejected"

RUNTIME_DOT="opportunistic"
test::capture dns::validate::global_runtime "$DNS_PROFILE_GOOGLE_CLOUDFLARE"
test::assert::equals "4" "$TEST_STATUS" "runtime mismatch status"
test::assert::equals $'runtime_mismatch\tDNSOverTLS\tyes\topportunistic' \
    "$TEST_OUTPUT" "runtime mismatch issue"

printf 'ID=ubuntu\nVERSION_ID=22.04\n' > "$OS_RELEASE_FILE_PATH"
RUNTIME_DNS=""
RUNTIME_DOMAINS=""
RUNTIME_DOT=""
dns::validate::global_runtime "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
    test::fail "empty systemd 249 runtime values were rejected"
printf 'ID=ubuntu\nVERSION_ID=24.04\n' > "$OS_RELEASE_FILE_PATH"

(
    VALIDATE_CALLS=""

    # Test doubles intentionally record validation order.
    dns::config::is_owned() { VALIDATE_CALLS+="owned "; }
    dns::config::matches_profile() { VALIDATE_CALLS+="match "; }
    dns::validate::effective() { VALIDATE_CALLS+="effective "; }
    dns::runtime::stub_is_listening() { VALIDATE_CALLS+="stub "; }
    dns::check::local_resolver() { VALIDATE_CALLS+="local "; }
    dns::check::routes() { VALIDATE_CALLS+="routes "; }
    dns::check::late_conflict() { VALIDATE_CALLS+="conflict "; }
    dns::validate::global_runtime() { VALIDATE_CALLS+="runtime "; }
    dns::runtime::query_strict() { VALIDATE_CALLS+="strict "; }
    dns::validate::strict_runtime "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
        test::fail "mock strict runtime validation failed"
    test::assert::equals \
        "owned match effective stub local routes conflict runtime strict " \
        "$VALIDATE_CALLS" \
        "strict runtime validation order"
)

(
    VALIDATE_CALLS=""

    # Test doubles intentionally record protected-state composition.
    dns::check::mode() { VALIDATE_CALLS+="mode "; }
    dns::validate::strict_runtime() { VALIDATE_CALLS+="strict "; }
    dns::runtime::query_libc() { VALIDATE_CALLS+="libc "; }

    dns::validate::protected "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
        test::fail "mock protected validation failed"
    test::assert::equals \
        "mode strict libc " \
        "$VALIDATE_CALLS" \
        "protected validation order"
)

printf 'All DNS protected-state validation tests passed\n'
