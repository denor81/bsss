sync() {
    if [[ "${1:-}" == "-f" && "${2:-}" == "${TEST_TMP}/etc" ]]; then
        SYNC_ETC=1
    fi
}

# @type:        Source
# @description: Reports real file metadata with root uid/gid for ownership tests
# @params:      options stat options and path
# @stdin:       None
# @stdout:      Requested metadata
# @exit_code:   $? real stat status
stat() {
    local option="$1"
    local format="$2"
    local path="$3"
    local mode links type size device inode

    [[ "$option" == "-c" ]] || return 1
    mode=$(/usr/bin/stat -c '%a' "$path") || return 1
    links=$(/usr/bin/stat -c '%h' "$path") || return 1
    type=$(/usr/bin/stat -c '%F' "$path") || return 1
    size=$(/usr/bin/stat -c '%s' "$path") || return 1
    device=$(/usr/bin/stat -c '%d' "$path") || return 1
    inode=$(/usr/bin/stat -c '%i' "$path") || return 1

    case "$format" in
        $'%u\t%g\t%a') printf '0\t0\t%s\n' "$mode" ;;
        $'%u\t%g\t%a\t%h\t%F') printf '0\t0\t%s\t%s\t%s\n' "$mode" "$links" "$type" ;;
        $'%u\t%g\t%h\t%F') printf '0\t0\t%s\t%s\n' "$links" "$type" ;;
        $'%s\t%u\t%g\t%a') printf '%s\t0\t0\t%s\n' "$size" "$mode" ;;
        $'%d\t%i\t%s\t%u\t%g\t%a') printf '%s\t%s\t%s\t0\t0\t%s\n' "$device" "$inode" "$size" "$mode" ;;
        *) return 1 ;;
    esac
}

# @type:        Orchestrator
# @description: Mocks resolver service state used by mode classification
# @stdin:       None
# @stdout:      None
# @exit_code:   0 active when requested
#               1 inactive
systemctl() {
    [[ "${1:-}" == "is-active" ]] || return 1
    (( MOCK_RESOLVED_ACTIVE == 1 ))
}

source "${PROJECT_ROOT}/modules/helpers/dns.sh"

# @type:        Source
# @description: Mocks exact baseline unit properties
# @params:      service Unit name (string) without a terminator
#               property Property name (string) without a terminator
# @stdin:       None
# @stdout:      property_value\n
# @exit_code:   0 always
dns::service::get_property() {
    local service="$1"
    local property="$2"

    case "${service}:${property}" in
        "${DNS_RESOLVED_SERVICE}:LoadState") printf 'loaded\n' ;;
        "${DNS_RESOLVED_SERVICE}:UnitFileState") printf 'disabled\n' ;;
        "${DNS_RESOLVED_SERVICE}:ActiveState") printf 'inactive\n' ;;
        "${DNS_RESOLVED_SERVICE}:SubState") printf 'dead\n' ;;
        "${DNS_NETWORKD_SERVICE}:ActiveState") printf 'active\n' ;;
        "${DNS_NETWORKD_SERVICE}:SubState") printf 'running\n' ;;
        "${DNS_NETWORK_MANAGER_SERVICE}:ActiveState") printf 'inactive\n' ;;
        *) return 1 ;;
    esac
}

printf '%s\n' \
    '# direct resolver' \
    'nameserver 8.8.8.8' \
    'nameserver 2001:4860:4860::8888' > "$DNS_RESOLV_CONF_PATH"
dns::direct::content_is_supported "$DNS_RESOLV_CONF_PATH" ||
    test::fail "valid IPv4 and IPv6 nameservers were rejected"

for invalid in \
    'search example.com' \
    'nameserver dns.google' \
    'nameserver fe80::1%eth0' \
    'nameserver 999.1.1.1' \
    'nameserver 2001:::1'; do
    printf '%s\n' "$invalid" > "$DNS_RESOLV_CONF_PATH"
    if dns::direct::content_is_supported "$DNS_RESOLV_CONF_PATH"; then
        test::fail "unsupported resolver row was accepted: $invalid"
    fi
done

printf '%s\n' 'nameserver 8.8.8.8' > "$DNS_RESOLV_CONF_PATH"
mode=$(dns::resolver::get_mode | tr -d '\0')
test::assert::equals "networkd-direct" "$mode" "direct mode"

ln -s "$DNS_RESOLVED_STUB_PATH" "${TEST_TMP}/etc/resolv.stub"
mv -T "${TEST_TMP}/etc/resolv.stub" "$DNS_RESOLV_CONF_PATH"
MOCK_RESOLVED_ACTIVE=1
mode=$(dns::resolver::get_mode | tr -d '\0')
test::assert::equals "resolved-stub" "$mode" "stub mode"
rm "$DNS_RESOLV_CONF_PATH"
MOCK_RESOLVED_ACTIVE=0
printf '%s\n' 'nameserver 8.8.8.8' > "$DNS_RESOLV_CONF_PATH"

exec {busy_fd}> "$DNS_PREPARE_LOCK_FILE"
flock -n "$busy_fd"
if dns::prepare::lock; then
    test::fail "busy preparation lock was acquired"
fi
exec {busy_fd}>&-
dns::prepare::lock || test::fail "free preparation lock was not acquired"
dns::prepare::unlock

dns::prepare::create_bundle "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
    test::fail "preparation bundle creation failed"
bundle=$(dns::prepare::read_bundle "$DNS_PREPARE_DIR" | tr -d '\0')
test::assert::equals \
    "${DNS_PROFILE_GOOGLE_CLOUDFLARE}"$'\t'"$(sha256sum "$DNS_RESOLV_CONF_PATH" | gawk '{ print $1 }')" \
    "$bundle" \
    "bundle state"
cmp --silent "$DNS_RESOLV_CONF_PATH" "$DNS_PREPARE_BACKUP_FILE" ||
    test::fail "resolver backup bytes differ"

mode=$(dns::resolver::get_mode | tr -d '\0')
test::assert::equals "interrupted" "$mode" "interrupted mode"

cp "$DNS_RESOLV_CONF_PATH" "${TEST_TMP}/expected-resolv.conf"
dns::prepare::switch_to_stub || test::fail "stub switch failed"
[[ -L "$DNS_RESOLV_CONF_PATH" ]] || test::fail "stub switch did not install a symlink"
SYNC_ETC=0
dns::prepare::restore_resolv_conf || test::fail "resolver file restoration failed"
(( SYNC_ETC == 1 )) || test::fail "restored resolver file was not flushed"
cmp --silent "${TEST_TMP}/expected-resolv.conf" "$DNS_RESOLV_CONF_PATH" ||
    test::fail "restored resolver bytes differ"

dns::prepare::cleanup_bundle || test::fail "bundle cleanup failed"
[[ ! -e "$DNS_PREPARE_DIR" && ! -e "$DNS_PREPARE_CLEANUP_DIR" ]] ||
    test::fail "bundle cleanup left artifacts"

mkdir -m 700 "$DNS_PREPARE_STAGING_DIR"
touch "${DNS_PREPARE_STAGING_DIR}/state"
chmod 600 "${DNS_PREPARE_STAGING_DIR}/state"
dns::prepare::partial_is_owned "$DNS_PREPARE_STAGING_DIR" ||
    test::fail "owned partial staging directory was rejected"
dns::prepare::remove_partial "$DNS_PREPARE_STAGING_DIR" ||
    test::fail "owned partial staging directory was not removed"

mkdir -m 700 "$DNS_PREPARE_STAGING_DIR"
touch "${DNS_PREPARE_STAGING_DIR}/foreign"
if dns::prepare::partial_is_owned "$DNS_PREPARE_STAGING_DIR"; then
    test::fail "foreign partial staging entry was accepted"
fi
rm "${DNS_PREPARE_STAGING_DIR}/foreign"
rmdir "$DNS_PREPARE_STAGING_DIR"

ln -s "$DNS_RESOLVED_STUB_PATH" "$DNS_PREPARE_TEMP_LINK"
dns::prepare::remove_temp_link || test::fail "owned temporary symlink was not removed"
ln -s "/foreign/stub" "$DNS_PREPARE_TEMP_LINK"
if dns::prepare::remove_temp_link; then
    test::fail "foreign temporary symlink was removed"
fi
rm "$DNS_PREPARE_TEMP_LINK"

dns::prepare::create_bundle "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
    test::fail "rollback bundle creation failed"
mkdir -p "$DNS_RESOLVED_CONFIG_DIR"
dns::config::render "$DNS_PROFILE_GOOGLE_CLOUDFLARE" > "$BSSS_DNS_CONFIG_FILE"
dns::prepare::switch_to_stub || test::fail "rollback stub switch failed"
SYNC_ETC=0
ROLLBACK_ORDER=""

# @type:        Orchestrator
# @description: Verifies durable resolver restoration before service stop
# @stdin:       None
# @stdout:      None
# @exit_code:   0 restoration is durable
#               1 restoration is missing or not flushed
dns::service::stop_disable() {
    [[ -f "$DNS_RESOLV_CONF_PATH" && ! -L "$DNS_RESOLV_CONF_PATH" ]] || return 1
    (( SYNC_ETC == 1 )) || return 1
    ROLLBACK_ORDER+="stop "
}

# @type:        Sink
# @description: Records BSSS DNS target removal
# @stdin:       None
# @stdout:      None
# @exit_code:   0 target removed
dns::config::remove() {
    rm "$BSSS_DNS_CONFIG_FILE"
    ROLLBACK_ORDER+="remove "
}

# @type:        Orchestrator
# @description: Records direct resolver validation
# @stdin:       None
# @stdout:      None
# @exit_code:   0 always
dns::direct::validate_query() {
    ROLLBACK_ORDER+="query"
}

dns::prepare::rollback || test::fail "preparation rollback failed"
test::assert::equals "stop remove query" "$ROLLBACK_ORDER" "rollback order"
cmp --silent "${TEST_TMP}/expected-resolv.conf" "$DNS_RESOLV_CONF_PATH" ||
    test::fail "rollback did not restore exact resolver bytes"

dns::prepare::guard_full_rollback || test::fail "clean full rollback guard failed"
exec {guard_probe_fd}> "$DNS_PREPARE_LOCK_FILE"
if flock -n "$guard_probe_fd"; then
    test::fail "full rollback guard did not hold the preparation lock"
fi
exec {guard_probe_fd}>&-
dns::prepare::unlock

mkdir -m 700 "$DNS_PREPARE_STAGING_DIR"
if dns::prepare::guard_full_rollback; then
    test::fail "full rollback guard accepted a preparation artifact"
fi
dns::prepare::remove_partial "$DNS_PREPARE_STAGING_DIR"

