set -Eeuo pipefail

readonly PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
readonly TEST_TMP="$(mktemp -d "${TMPDIR:-/tmp}/bsss-dns-check-test.XXXXXX")"
trap 'rm -rf "$TEST_TMP"' EXIT

readonly OS_RELEASE_FILE_PATH="${TEST_TMP}/os-release"
readonly DNS_SUPPORTED_UBUNTU_VERSIONS="22.04|24.04|26.04"
readonly DNS_BOOTSTRAP_SUPPORTED_UBUNTU_VERSIONS="24.04"
readonly DNS_PROFILE_GOOGLE_CLOUDFLARE="google-cloudflare"
readonly DNS_PROFILE_YANDEX_GOOGLE="yandex-google"
readonly DNS_SERVERS_GOOGLE_CLOUDFLARE="8.8.8.8#dns.google 1.1.1.1#one.one.one.one"
readonly DNS_SERVERS_YANDEX_GOOGLE="77.88.8.8#common.dot.dns.yandex.net 8.8.8.8#dns.google"
readonly DNS_ENDPOINT_TIMEOUT_SECONDS=1
readonly DNS_QUERY_TIMEOUT_SECONDS=1
readonly DNS_TEST_DOMAIN="example.com"
readonly DNS_RESOLVED_SERVICE="systemd-resolved.service"
readonly DNS_NETWORKD_SERVICE="systemd-networkd.service"
readonly DNS_NETWORK_MANAGER_SERVICE="NetworkManager.service"
readonly DNS_RESOLV_CONF_PATH="${TEST_TMP}/etc/resolv.conf"
readonly DNS_RESOLVED_STUB_PATH="${TEST_TMP}/run/systemd/resolve/stub-resolv.conf"
readonly DNS_RESOLVED_CONFIG_DIR="${TEST_TMP}/etc/systemd/resolved.conf.d"
readonly BSSS_DNS_CONFIG_FILE_NAME="99-bsss-dot.conf"
readonly BSSS_DNS_CONFIG_FILE="${DNS_RESOLVED_CONFIG_DIR}/${BSSS_DNS_CONFIG_FILE_NAME}"
readonly BSSS_DNS_ROLLBACK_FILE="${BSSS_DNS_CONFIG_FILE}.bsss_backup"
readonly BSSS_STATE_DIR="${TEST_TMP}/var/lib/bsss"
readonly DNS_PREPARE_DIR="${BSSS_STATE_DIR}/dns-resolver"
readonly DNS_PREPARE_STAGING_DIR="${BSSS_STATE_DIR}/.dns-resolver.staging"
readonly DNS_PREPARE_CLEANUP_DIR="${BSSS_STATE_DIR}/.dns-resolver.cleanup"
readonly DNS_PREPARE_TEMP_LINK="${TEST_TMP}/etc/.resolv.conf.bsss_prepare"
readonly DNS_PREPARE_LOCK_FILE="${TEST_TMP}/run/lock/bsss-dns-prepare.lock"
readonly BSSS_MARKER_COMMENT="Generated by BSSS"
readonly HOSTS_FILE_PATH="${TEST_TMP}/etc/hosts"

mkdir -p "${TEST_TMP}/etc/systemd" "${TEST_TMP}/run/systemd/resolve"
printf 'ID=ubuntu\nVERSION_ID=24.04\n' > "$OS_RELEASE_FILE_PATH"
printf '127.0.0.1 localhost\n' > "$HOSTS_FILE_PATH"

source "${PROJECT_ROOT}/modules/helpers/dns/facade.sh"

TEST_STATUS=0
TEST_OUTPUT=""

# @type:        Sink
# @description: Fails the current test
# @params:      message Failure message (string) without a terminator
# @stdin:       None
# @stdout:      None
# @exit_code:   1 always
test::fail() {
    printf 'FAIL: %s\n' "$1" >&2
    exit 1
}

# @type:        Validator
# @description: Compares two strings
# @params:      expected Expected value (string) without a terminator
#               actual Actual value (string) without a terminator
#               label Assertion label (string) without a terminator
# @stdin:       None
# @stdout:      None
# @exit_code:   0 values match
#               1 values differ
test::assert::equals() {
    [[ "$2" == "$1" ]] || test::fail "$3: expected [$1], got [$2]"
}

# @type:        Orchestrator
# @description: Captures one check function status and NUL records
# @params:      command Function name (string) without a terminator
#               ... Function arguments (string) without a terminator
# @stdin:       None
# @stdout:      None
# @exit_code:   0 capture completed
test::capture() {
    local output_file="${TEST_TMP}/capture"

    : > "$output_file"
    if "$@" > "$output_file"; then
        TEST_STATUS=0
    else
        TEST_STATUS=$?
    fi
    TEST_OUTPUT=$(tr '\0' '\n' < "$output_file")
}

test::capture dns::check::block "sample_issue" "one" "two"
test::assert::equals "4" "$TEST_STATUS" "blocker status"
test::assert::equals $'sample_issue\tone\ttwo' "$TEST_OUTPUT" "blocker record"

test::capture dns::check::emit "sample_without_arguments"
test::assert::equals "0" "$TEST_STATUS" "argument-free issue status"
test::assert::equals $'sample_without_arguments\t' "$TEST_OUTPUT" "argument-free issue record"

test::capture dns::check::emit "sample_issue" $'bad\nfield'
test::assert::equals "1" "$TEST_STATUS" "malformed issue status"
test::assert::equals "" "$TEST_OUTPUT" "malformed issue output"

dns::check::compatibility "resolved-stub" ||
    test::fail "resolved-stub was rejected on Ubuntu 24.04"
dns::check::compatibility "networkd-direct" ||
    test::fail "networkd-direct was rejected on Ubuntu 24.04"

printf 'ID=ubuntu\nVERSION_ID=26.04\n' > "$OS_RELEASE_FILE_PATH"
test::capture dns::check::compatibility "networkd-direct"
test::assert::equals "4" "$TEST_STATUS" "direct release blocker status"
test::assert::equals $'unsupported_release\tnetworkd-direct\tubuntu\t26.04\t24.04' \
    "$TEST_OUTPUT" "direct release blocker"

dns::check::compatibility "interrupted" ||
    test::fail "recovery was blocked by release compatibility"
printf 'ID=ubuntu\nVERSION_ID=24.04\n' > "$OS_RELEASE_FILE_PATH"

test::capture dns::check::commands "command-that-must-not-exist-bsss"
test::assert::equals "4" "$TEST_STATUS" "missing command status"
test::assert::equals $'missing_command\tcommand-that-must-not-exist-bsss' \
    "$TEST_OUTPUT" "missing command issue"

mkdir -p "${TEST_TMP}/foreign-dir"
ln -s "${TEST_TMP}/foreign-dir" "$DNS_RESOLVED_CONFIG_DIR"
test::capture dns::check::config_dir
test::assert::equals "4" "$TEST_STATUS" "linked config directory status"
test::assert::equals "config_dir_unsafe	${DNS_RESOLVED_CONFIG_DIR}" \
    "$TEST_OUTPUT" "linked config directory issue"
rm "$DNS_RESOLVED_CONFIG_DIR"

dns::check::state_dir ||
    test::fail "absent state directory did not return success"

printf 'nameserver 8.8.8.8\nnameserver 2001:4860:4860::8888\n' > "$DNS_RESOLV_CONF_PATH"
dns::check::direct_content "$DNS_RESOLV_CONF_PATH" ||
    test::fail "valid direct resolver content was rejected"
printf 'search example.test\nnameserver 8.8.8.8\n' > "$DNS_RESOLV_CONF_PATH"
if dns::check::direct_content "$DNS_RESOLV_CONF_PATH"; then
    test::fail "unsupported direct resolver content was accepted"
fi

printf '127.0.0.1 localhost %s\n' "$DNS_TEST_DOMAIN" > "$HOSTS_FILE_PATH"
test::capture dns::check::test_name
test::assert::equals "4" "$TEST_STATUS" "local test name status"
test::assert::equals "test_name_local	${DNS_TEST_DOMAIN}" "$TEST_OUTPUT" "local test name issue"
printf '127.0.0.1 localhost\n' > "$HOSTS_FILE_PATH"

routes=$(
    cat << 'EOF' |
Global: ~.
Link 2 (ens3): ~corp.example example.test
EOF
        dns::runtime::parse_route_domains |
        tr '\0' '\n'
)
test::assert::equals $'ens3\t~corp.example\nens3\texample.test' "$routes" "route domain parsing"

(
    CHECK_CALLS=""

    dns::check::compatibility() { CHECK_CALLS+="compat "; }
    dns::check::mode() { CHECK_CALLS+="mode "; }
    dns::check::commands() { CHECK_CALLS+="commands "; }
    dns::runtime::stub_is_listening() { CHECK_CALLS+="stub "; }
    dns::check::local_resolver() { CHECK_CALLS+="local "; }
    dns::check::config_dir() { CHECK_CALLS+="dir "; }
    dns::check::target() { CHECK_CALLS+="target "; }
    dns::config::get_effective() { CHECK_CALLS+="effective "; }
    dns::check::routes() { CHECK_CALLS+="routes "; }
    dns::check::late_conflict() { CHECK_CALLS+="conflict "; }
    dns::check::endpoints() { CHECK_CALLS+="endpoints "; }

    dns::check::resolved "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
        test::fail "mock resolved preflight failed"
    test::assert::equals \
        "compat mode commands stub local dir target effective routes conflict endpoints " \
        "$CHECK_CALLS" \
        "resolved preflight order"
)

(
    CHECK_CALLS=""

    dns::check::compatibility() { CHECK_CALLS+="compat "; }
    dns::check::mode() { CHECK_CALLS+="mode "; }
    dns::check::commands() { CHECK_CALLS+="commands "; }
    dns::check::direct_file() { CHECK_CALLS+="file "; }
    dns::check::config_dir() { CHECK_CALLS+="dir "; }
    dns::check::state_dir() { CHECK_CALLS+="state "; }
    dns::check::local_resolver() { CHECK_CALLS+="local "; }
    dns::check::kernel_overrides() { CHECK_CALLS+="kernel "; }
    dns::check::test_name() { CHECK_CALLS+="hosts "; }
    dns::check::late_conflict() { CHECK_CALLS+="conflict "; }
    dns::check::direct_query() { CHECK_CALLS+="query "; }
    dns::check::endpoints() { CHECK_CALLS+="endpoints "; }

    dns::check::direct "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
        test::fail "mock direct preflight failed"
    test::assert::equals \
        "compat mode commands file dir state local kernel hosts conflict query endpoints " \
        "$CHECK_CALLS" \
        "direct preflight order"
)

(
    dns::check::resolved() { printf 'resolved'; }
    dns::check::direct() { printf 'direct'; }

    result=$(dns::check::apply "resolved-stub" "$DNS_PROFILE_GOOGLE_CLOUDFLARE")
    test::assert::equals "resolved" "$result" "resolved dispatcher"
    result=$(dns::check::apply "networkd-direct" "$DNS_PROFILE_GOOGLE_CLOUDFLARE")
    test::assert::equals "direct" "$result" "direct dispatcher"
)

test::capture dns::check::apply "interrupted" "$DNS_PROFILE_GOOGLE_CLOUDFLARE"
test::assert::equals "4" "$TEST_STATUS" "recovery-required status"
test::assert::equals $'recovery_required\t' "$TEST_OUTPUT" "recovery-required issue"

if dns::check::apply "resolved-stub" "unknown" >/dev/null; then
    test::fail "unsupported profile was accepted"
else
    status=$?
fi
test::assert::equals "1" "$status" "unsupported profile status"

printf 'All DNS preflight component tests passed\n'
