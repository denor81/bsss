set -Eeuo pipefail

readonly PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
readonly TEST_TMP="$(mktemp -d "${TMPDIR:-/tmp}/bsss-dns-resolved-test.XXXXXX")"
trap 'rm -rf "$TEST_TMP"' EXIT

readonly DNS_PROFILE_GOOGLE_CLOUDFLARE="google-cloudflare"
readonly DNS_PROFILE_YANDEX_GOOGLE="yandex-google"
readonly DNS_SERVERS_GOOGLE_CLOUDFLARE="8.8.8.8#dns.google 1.1.1.1#one.one.one.one"
readonly DNS_SERVERS_YANDEX_GOOGLE="77.88.8.8#common.dot.dns.yandex.net 8.8.8.8#dns.google"
readonly DNS_TEST_DOMAIN="example.com"
readonly DNS_RESOLVED_SERVICE="systemd-resolved.service"
readonly DNS_RESOLVED_CONFIG_DIR="${TEST_TMP}/etc/systemd/resolved.conf.d"
readonly BSSS_DNS_CONFIG_FILE_NAME="99-bsss-dot.conf"
readonly BSSS_DNS_CONFIG_FILE="${DNS_RESOLVED_CONFIG_DIR}/${BSSS_DNS_CONFIG_FILE_NAME}"
readonly BSSS_DNS_ROLLBACK_FILE="${BSSS_DNS_CONFIG_FILE}.bsss_backup"
readonly BSSS_MARKER_COMMENT="Generated by BSSS"

mkdir -p "$DNS_RESOLVED_CONFIG_DIR"

source "${PROJECT_ROOT}/modules/helpers/dns/config.sh"
source "${PROJECT_ROOT}/modules/helpers/dns/resolved.sh"

test::fail() {
    printf 'FAIL: %s\n' "$1" >&2
    exit 1
}

test::assert::equals() {
    [[ "$2" == "$1" ]] || test::fail "$3: expected [$1], got [$2]"
}

chown() {
    return
}

dns::resolved::restart() {
    return
}

dns::resolved::flush_cache() {
    return
}

dns::resolved::validate_standard() {
    return
}

dns::resolved::install "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
    test::fail "atomic profile install failed"
dns::config::matches_profile "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
    test::fail "installed profile content differs"

original_content=$(cat "$BSSS_DNS_CONFIG_FILE")
dns::resolved::snapshot ||
    test::fail "owned target snapshot failed"
printf '# %s\nchanged\n' "$BSSS_MARKER_COMMENT" > "$BSSS_DNS_CONFIG_FILE"
dns::resolved::restore ||
    test::fail "snapshot restore failed"
restored_content=$(cat "$BSSS_DNS_CONFIG_FILE")
test::assert::equals "$original_content" "$restored_content" "exact snapshot restore"
[[ ! -e "$BSSS_DNS_ROLLBACK_FILE" ]] ||
    test::fail "restore left transaction snapshot"

rm "$BSSS_DNS_CONFIG_FILE"
dns::resolved::snapshot ||
    test::fail "absent target snapshot failed"
dns::resolved::install "$DNS_PROFILE_YANDEX_GOOGLE" ||
    test::fail "new target install failed"
dns::resolved::restore ||
    test::fail "new target rollback failed"
[[ ! -e "$BSSS_DNS_CONFIG_FILE" ]] ||
    test::fail "new target rollback did not remove target"
dns::resolved::cleanup ||
    test::fail "absent transaction snapshot did not return success"

printf '# foreign\n' > "$BSSS_DNS_CONFIG_FILE"
printf '# %s\noriginal\n' "$BSSS_MARKER_COMMENT" > "$BSSS_DNS_ROLLBACK_FILE"
if dns::resolved::restore; then
    test::fail "restore overwrote a concurrent foreign target"
fi
grep -Fxq '# foreign' "$BSSS_DNS_CONFIG_FILE" ||
    test::fail "foreign target changed after refused restore"
rm "$BSSS_DNS_CONFIG_FILE" "$BSSS_DNS_ROLLBACK_FILE"

(
    APPLY_CALLS=""

    dns::check::apply() { APPLY_CALLS+="check "; }
    dns::config::matches_profile() { return 1; }
    dns::resolved::snapshot() { APPLY_CALLS+="snapshot "; }
    dns::resolved::install() { APPLY_CALLS+="install "; }
    dns::resolved::restart() { APPLY_CALLS+="restart "; }
    dns::resolved::flush_cache() { APPLY_CALLS+="flush "; }
    dns::validate::protected() { APPLY_CALLS+="validate "; }
    dns::resolved::cleanup() { APPLY_CALLS+="cleanup "; }

    dns::resolved::apply "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
        test::fail "mock successful transaction failed"
    test::assert::equals \
        "check snapshot install restart flush validate cleanup " \
        "$APPLY_CALLS" \
        "successful transaction order"
)

(
    APPLY_CALLS=""

    dns::check::apply() { APPLY_CALLS+="check "; }
    dns::config::matches_profile() { return 1; }
    dns::resolved::snapshot() { APPLY_CALLS+="snapshot "; }
    dns::resolved::install() { APPLY_CALLS+="install "; }
    dns::resolved::restart() { APPLY_CALLS+="restart "; }
    dns::resolved::flush_cache() { APPLY_CALLS+="flush "; }
    dns::validate::protected() {
        APPLY_CALLS+="validate "
        return 4
    }
    dns::resolved::rollback() {
        APPLY_CALLS+="rollback "
        return 3
    }

    if dns::resolved::apply "$DNS_PROFILE_GOOGLE_CLOUDFLARE"; then
        test::fail "failed post-validation returned success"
    else
        status=$?
    fi
    test::assert::equals "3" "$status" "successful rollback status"
    test::assert::equals \
        "check snapshot install restart flush validate rollback " \
        "$APPLY_CALLS" \
        "failed validation rollback order"
)

(
    APPLY_CALLS=""

    dns::check::apply() { APPLY_CALLS+="check "; }
    dns::config::matches_profile() { return 1; }
    dns::resolved::snapshot() { APPLY_CALLS+="snapshot "; }
    dns::resolved::install() {
        APPLY_CALLS+="install "
        return 1
    }
    dns::resolved::rollback() {
        APPLY_CALLS+="rollback "
        return 3
    }

    if dns::resolved::apply "$DNS_PROFILE_GOOGLE_CLOUDFLARE"; then
        test::fail "failed mutation returned success"
    else
        status=$?
    fi
    test::assert::equals "3" "$status" "mutation rollback status"
    test::assert::equals \
        "check snapshot install rollback " \
        "$APPLY_CALLS" \
        "failed mutation rollback order"
)

(
    dns::check::apply() { return; }
    dns::config::matches_profile() { return 1; }
    dns::resolved::snapshot() { return; }
    dns::resolved::install() { return 1; }
    dns::resolved::rollback() { return 1; }

    if dns::resolved::apply "$DNS_PROFILE_GOOGLE_CLOUDFLARE"; then
        test::fail "failed rollback returned success"
    else
        status=$?
    fi
    test::assert::equals "1" "$status" "failed rollback status"
)

(
    dns::check::apply() { return 4; }
    dns::resolved::snapshot() { test::fail "snapshot ran after failed preflight"; }

    if dns::resolved::apply "$DNS_PROFILE_GOOGLE_CLOUDFLARE"; then
        test::fail "failed preflight returned success"
    else
        status=$?
    fi
    test::assert::equals "4" "$status" "preflight status propagation"
)

(
    dns::check::apply() { return; }
    dns::config::matches_profile() { return; }
    dns::validate::protected() { return; }
    dns::resolved::snapshot() { test::fail "snapshot ran for unchanged profile"; }

    dns::resolved::apply "$DNS_PROFILE_GOOGLE_CLOUDFLARE" ||
        test::fail "unchanged profile validation failed"
)

printf 'All DNS resolved-stub transaction tests passed\n'
